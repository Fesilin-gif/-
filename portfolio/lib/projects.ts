/* ============================================================
   Проекты портфолио — единственный источник данных.
   ------------------------------------------------------------
   Компоненты только раскладывают этот список по экрану.
   Ничего не выдумано: слоты пустые, их нужно заполнить
   своими названиями, описаниями и ссылками.
   ============================================================ */

export type ProjectMedallion = {
  /** Картинка внутри круга. Пока не задана — рисуется живописная заглушка. */
  src: string;
  alt: string;
  width: number;
  height: number;
  /** Точка кадрирования круга, если важная часть не в центре. */
  focus?: string;
};

export type Project = {
  /**
   * Стабильный ключ. Он же будущий сегмент адреса кейса: /case/<id>.
   * Менять его после публикации — значит ломать ссылки.
   */
  id: string;

  /** Название сайта. ЗАПОЛНИТЬ. */
  title: string | null;

  /** Одна строка под названием: что это за сайт. ЗАПОЛНИТЬ. */
  summary: string | null;

  /** Год, роль, стек — короткие метки под медальоном. Необязательно. */
  meta?: readonly string[];

  /**
   * Страница кейса внутри портфолио. Пока её нет — оставить null:
   * медальон тогда не ссылка, а кнопка выбора, и ничего не ведёт
   * в пустоту. Появится страница — впишите сюда '/case/<id>'.
   */
  caseHref: string | null;

  /** Ссылка на живой сайт. Необязательно. */
  liveHref?: string | null;

  medallion?: ProjectMedallion;
};

/**
 * Подпись на месте незаполненного названия. Это не название проекта,
 * а видимая метка-заглушка: пока она на экране, слот не готов.
 */
export const EMPTY_SLOT_LABEL = 'Слот проекта';

/**
 * Слоты портфолио.
 *
 * Добавить проект — добавить объект в массив: ряд медальонов и вся
 * раскладка сцены пересчитываются сами, в коде править нечего.
 * Комфортный ряд — от трёх до шести медальонов.
 */
export const PROJECTS: readonly Project[] = [
  { id: 'slot-01', title: null, summary: null, caseHref: null },
  { id: 'slot-02', title: null, summary: null, caseHref: null },
  { id: 'slot-03', title: null, summary: null, caseHref: null },
] as const;

/** Номер медальона в ряду — «01», «02», … */
export const ordinal = (index: number) => String(index + 1).padStart(2, '0');
