/* ============================================================
   Геометрия сцены «отъезд камеры»
   ------------------------------------------------------------
   Здесь только чистые вычисления: никакого DOM, никаких
   побочных эффектов. Компонент ArchScene измеряет экран,
   зовёт эти функции и раскладывает результат по transform.

   Один слой, одна система координат
   ----------------------------------
   Нет отдельного «пейзажа на первом экране» и отдельного «вида
   в проёме» — это один и тот же элемент <img> с одним и тем же
   файлом на всём протяжении сцены. Никакой смены источника,
   никакого перекрёстного затухания между двумя картинками.

   Устроено это через общий контейнер — .rig, размером ровно
   с натуральный кадр арки (1122×1402 = ARCH.width×ARCH.height).
   Внутри него, в ЭТИХ ЖЕ координатах:
     - .rig__window — обёртка размером ровно с сам .rig (те же
       1122×1402), НЕПОДВИЖНАЯ и с ПОСТОЯННОЙ маской: mask-size
       100% 100%, mask-position 0 0 — сама обёртка и есть система
       координат маски, пересчитывать нечего. Маска — точная
       готическая форма проёма (arch-opening-mask.png, тот же файл,
       что и точный контур самой арки — один источник истины);
     - панорама — <img> ВНУТРИ обёртки, со своим отдельным transform,
       который может быть каким угодно (см. ниже, "панорама двух
       состояний") — маску это не касается вообще, у неё своя,
       фиксированная система координат;
     - фигура арки (arch-transparent.png) — тот же кадр 1122×1402,
       без собственного transform вообще: она просто СОВПАДАЕТ
       с координатами .rig, пиксель в пиксель, но её НЕПРОЗРАЧНОСТЬ
       анимируется (см. PHASE.figureIn) — на самом первом экране её
       не должно быть видно вовсе, только пейзаж.
   Сам .rig двигается одним transform (translate + scale), который
   каждый кадр прокрутки пишет ArchScene.tsx — им масштабируются
   и обёртка с маской и панорамой внутри, и фигура арки разом.

   На старте (progress 0) .rig взят настолько огромным, что даже его
   проём с запасом перекрывает весь экран (computeLayout →
   fitOpeningCover) — рамка (и то, что маска вырезает под силуэт
   девушки) гарантированно вне экрана. Фигура арки на этом же участке
   ещё и прозрачна (PHASE.figureIn заканчивается раньше, чем .rig
   успевает сжаться настолько, что его проём перестаёт перекрывать
   экран с запасом, — см. проверку в самом низу файла) — то есть
   «не должно быть видно вовсе» держится и на geometрии (рамка вне
   экрана), и на непрозрачности (запас на случай, если что-то из
   этого чуть-чуть не рассчитано под конкретный экран).

   Панорама двух состояний
   ------------------------
   Единственное усложнение поверх этой схемы: местоположение самой
   панорамы ВНУТРИ обёртки — это не константа, а функция прогресса,
   landscapeRectAt. У неё два опорных состояния:
     - на входе (progress 0) — landscapeStartRect: панорама подобрана
       так, что в сочетании со стартовым (огромным) .rig на экране
       получается ровно то же самое, что fitCoverFocused дал бы для
       простого полноэкранного фона — прямой pixel-perfect расчёт
       («если .rig взять вот таким огромным — то какой локальный
       кусочек панорамы под этот масштаб даст на экране обычный
       полноэкранный кадр»), а не приближение на глаз. Масштаб этого
       кусочка получается маленьким — но, в отличие от более ранней
       версии этой сцены, это больше не влияет на маску вообще: маска
       — свойство неподвижной обёртки, а не панорамы, и не зависит
       от того, насколько сильно панорама внутри нее растянута;
     - на выходе — тот же localViewRect, что и раньше: панорама,
       подогнанная под сам проём.
   Между ними — тот же приём, что и у rigRectAt: геометрический
   интерфит масштаба плюс линейный интерфит опорной точки (фокус
   вида), чтобы кадр не «плыл», а стягивался к одной точке. Это ОДИН
   и тот же <img> с ОДНИМ и тем же файлом на всём протяжении сцены —
   меняется только его собственное положение внутри обёртки, откуда
   каждый кадр прокрутки пересчитывается его transform, по формуле,
   а не подгонкой по времени. Смены источника или перекрёстного
   затухания здесь как не было, так и нет.

   Итог: на самом первом экране виден только пейзаж, обычным
   полноэкранным кадром, без арки и девушки вовсе. При прокрутке
   девушка с аркой проявляются (PHASE.figureIn — непрозрачность
   фигуры) и одновременно с этим и сам .rig, и локальное положение
   панорамы внутри него едут к финальному состоянию — камень входит
   в кадр со всех сторон, а пейзаж внутри проёма плавно «отдаляется»
   от широкого кадра к точной обрезке по форме окна.
   ============================================================ */

