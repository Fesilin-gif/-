/**
 * Полная раскладка сцены.
 *
 * viewport — экран (высота берётся у самого stage, а не у window:
 *   на телефоне адресная строка меняет высоту окна, а не блока).
 * frame — свободная середина экрана между заголовком и медальонами.
 *   Её размер компонент измеряет у реального пустого элемента, поэтому
 *   композиция сама подстраивается под длину заголовка, количество
 *   медальонов и любой размер шрифта.
 */
/** Насколько выше геометрического центра рамки встаёт финальная арка
 *  по вертикали — 0.5 было бы точно по центру, меньше — выше. */
const ARCH_VERTICAL_ANCHOR = 0.4;

/**
 * То же самое, но для СТАРТА отъезда (rigStart), и гораздо резче.
 *
 * .rig на старте настолько огромен (много выше экрана), что свод арки
 * и подол платья физически не помещаются в экран одновременно — при
 * любой точке привязки что-то одно обрезано верхним/нижним краем.
 * Раз выбирать всё равно приходится, лучше обрезать подол (он в любом
 * случае ещё не виден целиком — девушка только проявляется, см.
 * PHASE.figureIn), чем свод: подпись «тут арка должна быть выше»
 * была именно про срезанный свод в середине прокрутки. Чем ближе эта
 * точка к верху экрана на старте, тем раньше (по прогрессу) свод
 * перестаёт обрезаться — сама точка при этом всё равно едет к
 * ARCH_VERTICAL_ANCHOR линейно, так что рывка нет.
 */
const RIG_START_VERTICAL_ANCHOR = 0;

export function computeLayout(viewport: Size, frame: Rect): SceneLayout {
  const arch = fitContentContain(ARCH, ARCH.content, frame, { x: 0.5, y: ARCH_VERTICAL_ANCHOR });

  const rigStart = fitOpeningCover(
    { x: 0, y: 0, width: viewport.width, height: viewport.height },
    1.2,
    { x: 0.5, y: RIG_START_VERTICAL_ANCHOR },
  );

  return { arch, rigStart };
}

/**
 * Положение .rig (кадр 1122×1402) на произвольном прогрессе —
 * единственная анимация сцены. Масштаб идёт геометрически: равные
 * шаги прокрутки — равные ДОЛИ изменения размера, а не равные
 * пиксели, — так ведёт себя настоящий отъезд камеры, темп читается
 * ровным на всём пути.
 */
export function rigRectAt(progress: number, from: Rect, to: Rect): Rect {
  const t = phase(progress, PHASE.pullBack);

  const width = from.width * Math.pow(to.width / from.width, t);
  const height = width * (ARCH.height / ARCH.width);

  const anchorX = lerp(
    from.x + OPENING_CENTER.x * from.width,
    to.x + OPENING_CENTER.x * to.width,
    t,
  );
  const anchorY = lerp(
    from.y + OPENING_CENTER.y * from.height,
    to.y + OPENING_CENTER.y * to.height,
    t,
  );

  return {
    x: anchorX - OPENING_CENTER.x * width,
    y: anchorY - OPENING_CENTER.y * height,
    width,
    height,
  };
}

/**
 * transform для слоя. Слой лежит в натуральном размере кадра в
 * левом верхнем углу сцены (transform-origin: 0 0), поэтому одна
 * матрица переносит и масштабирует его без пересчёта вёрстки.
 */
export function transformFor(rect: Rect, source: Size): string {
  const scale = rect.width / source.width;
  return `translate3d(${rect.x.toFixed(2)}px, ${rect.y.toFixed(2)}px, 0) scale(${scale.toFixed(5)})`;
}

/**
 * Запас поверх точного cover-кадра — см. localViewRect. Прямоугольник
 * проёма (396×740 в натуральных пикселях) заметно уже, чем пропорции
 * самой панорамы (1672×941), поэтому «cover» упирается в высоту:
 * готовый кадр накрывает проём по высоте РОВНО, без единого лишнего
 * пикселя запаса (по ширине запас огромный). Margin здесь ни на что
 * не влияет визуально — лишние пиксели кадра всё равно срезает маска
 * проёма, — это только про landscapeRectAt ниже: пока .rig едет от
 * landscapeStartRect к этому кадру, опорная точка вида идёт по прямой
 * между двумя РАЗНЫМИ позициями, и где-то в середине пути кадр
 * неизбежно проходит через положение, чуть отличное от «ровно
 * впритык». Без запаса это положение на пару кадров прокрутки
 * приоткрывает белый холст по нижнему краю проёма — проверено
 * скриншотами на progress≈0.5.
 */
const FINAL_VIEW_MARGIN = 1.4;

/**
 * Где именно внутри .rig__window (в натуральных пикселях 1122×1402)
 * должен встать вид, чтобы накрыть проём — то же самое, что раньше
 * называлось «вид в проёме»: панорама, подогнанная под точную форму
 * готического проёма (cover, focus — точка интереса вида), с запасом
 * — см. FINAL_VIEW_MARGIN.
 */
export function localViewRect(view: WindowView): Rect {
  const rect = fitCoverFocused(view, OPENING_LOCAL, view.focus ?? { x: 0.5, y: 0.5 });
  const width = rect.width * FINAL_VIEW_MARGIN;
  const height = rect.height * FINAL_VIEW_MARGIN;
  return {
    x: rect.x - (width - rect.width) / 2,
    y: rect.y - (height - rect.height) / 2,
    width,
    height,
  };
}

/**
 * Локальное положение вида внутри .rig__window на progress 0: такое,
 * что в паре со стартовым (огромным) кадром .rig на экране получается
 * ровно fitCoverFocused(view, viewport, focus) — обычный полноэкранный
 * фон, как если бы арки не было вовсе. Не приближение — точный
 * обратный расчёт: rigStart уже даёт экранный transform
 * (translate+scale), здесь тот же экранный кадр вида просто
 * выражается в ЛОКАЛЬНЫХ координатах .rig (делим на transform
 * rigStart). Получающийся масштаб обычно намного меньше, чем у
 * localViewRect, — но, в отличие от более ранней версии сцены, на
 * маску это никак не влияет (см. заголовок файла): можно спокойно
 * использовать любой масштаб.
 */
export function landscapeStartRect(view: WindowView, viewport: Size, rigStart: Rect): Rect {
  const screen = fitCoverFocused(
    view,
    { x: 0, y: 0, width: viewport.width, height: viewport.height },
    view.focus ?? { x: 0.5, y: 0.5 },
  );
  const rigScale = rigStart.width / ARCH.width;
  return {
    x: (screen.x - rigStart.x) / rigScale,
    y: (screen.y - rigStart.y) / rigScale,
    width: screen.width / rigScale,
    height: screen.height / rigScale,
  };
}

/**
 * Локальное положение вида внутри .rig__window на произвольном
 * прогрессе — тем же приёмом, что и rigRectAt: геометрический
 * интерфит масштаба (равные доли изменения размера на равных шагах
 * прокрутки) и линейный интерфит экранного положения опорной точки
 * вида (focus — та же точка интереса, что и у fitCoverFocused), чтобы
 * кадр стягивался к ней, а не «плыл». from обычно — landscapeStartRect,
 * to — localViewRect(view); идёт по PHASE.landscapeSettle — короче, чем
 * у самого .rig (PHASE.pullBack), см. её комментарий, почему это не
 * ломает ощущение непрерывного отъезда.
 */
export function landscapeRectAt(progress: number, from: Rect, to: Rect, focus: Point): Rect {
  const t = phase(progress, PHASE.landscapeSettle);

  const width = from.width * Math.pow(to.width / from.width, t);
  const height = from.height * Math.pow(to.height / from.height, t);

  const anchorX = lerp(from.x + focus.x * from.width, to.x + focus.x * to.width, t);
  const anchorY = lerp(from.y + focus.y * from.height, to.y + focus.y * to.height, t);

  return {
    x: anchorX - focus.x * width,
    y: anchorY - focus.y * height,
    width,
    height,
  };
}
